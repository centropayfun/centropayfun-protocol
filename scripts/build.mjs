// Static build: src/ → dist/ (override with CENTRO_OUT). Optional register overrides:
//   CENTRO_CA, CENTRO_X, CENTRO_GITHUB  (used to prove both gate branches)
import { cpSync, mkdirSync, rmSync, readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, process.env.CENTRO_OUT || 'dist');
const src = join(root, 'src');
if (out === root || !out.startsWith(root)) throw new Error('output must live inside the project folder');

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const files = ['index.html', 'tokens.css', 'styles.css'];
for (const f of files) cpSync(join(src, f), join(out, f));
cpSync(join(src, 'js'), join(out, 'js'), { recursive: true });
cpSync(join(src, 'assets'), join(out, 'assets'), { recursive: true });   // logo-512/192/64, app-preview
cpSync(join(src, 'assets', 'favicon.svg'), join(out, 'favicon.svg'));

// register data, with optional overrides
const reg = structuredClone((await import(pathToFileURL(join(src, 'register-data.js')).href)).default);
if (process.env.CENTRO_CA) reg.ca = { state: 'stated', value: process.env.CENTRO_CA };
if (process.env.CENTRO_X) reg.x = { state: 'stated', url: process.env.CENTRO_X };
if (process.env.CENTRO_GITHUB) reg.github = { state: 'stated', url: process.env.CENTRO_GITHUB };
writeFileSync(join(out, 'register-data.js'), `// generated by scripts/build.mjs\nexport default ${JSON.stringify(reg, null, 2)};\n`);

// ---- guards: logo must be in dist and referenced with a correct relative path ----
const html = readFileSync(join(out, 'index.html'), 'utf8');
const problems = [];
for (const rel of ['assets/logo-512.png', 'assets/logo-192.png', 'assets/logo-64.png', 'favicon.svg']) {
  if (!existsSync(join(out, rel))) problems.push(`missing in output: ${rel}`);
  if (!html.includes(`"${rel}"`)) problems.push(`index.html does not reference "${rel}"`);
}
if (/(?:src|href)="\//.test(html)) problems.push('index.html contains root-absolute paths');
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }

const list = (d, p = '') => readdirSync(d).flatMap((n) => statSync(join(d, n)).isDirectory() ? list(join(d, n), p + n + '/') : [p + n]);
console.log(`build ok → ${out}\n  files: ${list(out).join(', ')}\n  ca=${reg.ca.state} x=${reg.x.state} github=${reg.github.state}`);
